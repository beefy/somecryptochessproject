"""Write the browser's copy of the BIP-39 English wordlist.

The wallet backs a keyfile up as 24 words, so the browser needs the exact list the
CLI uses. Rather than vendor a second BIP-39 dependency, this copies the list out
of the `mnemonic` package that `sccp.crypto.wallet` already imports, which makes
the two implementations agree by construction:

    python scripts/make_web_wordlist.py

Run it only when the dependency's list changes (it is a fixed standard, so in
practice: never). ``src/web/src/lib/mnemonic.test.ts`` pins a phrase generated by
the Python module, so a drift fails the vitest run.
"""

from __future__ import annotations

from pathlib import Path

WORDLIST = Path("src/web/src/lib/wordlist.ts")
"""Where the TypeScript module is written."""

def wordlist_path() -> Path:
    """The installed `mnemonic` package's English list."""
    import mnemonic

    return Path(mnemonic.__file__).resolve().parent / "wordlist" / "english.txt"


def render(words: list[str]) -> str:
    """The TypeScript module holding ``words`` in index order."""
    header = """/**
 * The BIP-39 English wordlist: 2048 words, one per line, in index order.
 *
 * It is data, not code, but it has to ship with the bundle: a 24-word backup
 * phrase is only lossless if the reader knows the exact list the writer used.
 * Generated by `scripts/make_web_wordlist.py` from the `mnemonic` package's
 * `english.txt`, which is the list `sccp.crypto.wallet.seed_to_mnemonic` uses,
 * so the two implementations agree word for word.
 */

export const BIP39_ENGLISH: readonly string[] = [
"""
    body = "".join(f'  "{word}",\n' for word in words)
    return header + body + "];\n"


def main() -> None:
    """Write ``src/web/src/lib/wordlist.ts`` from the installed wordlist."""
    words = wordlist_path().read_text(encoding="utf-8").split()
    if len(words) != 2048 or len(set(words)) != 2048:
        raise SystemExit(f"expected 2048 distinct words, got {len(words)}")
    target = Path(__file__).resolve().parents[1] / WORDLIST
    target.write_text(render(words), encoding="utf-8")
    print(f"wrote {target} with {len(words)} words")


if __name__ == "__main__":
    main()
