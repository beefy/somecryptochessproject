#!/usr/bin/env python3
"""Generate (or verify) the pinned genesis documents in ``genesis/``.

Genesis is the only premine, so it is generated by a script and committed: the
resulting hash is pinned in :class:`sccp.config.NetworkParams` and checked on
every load.

Testnet and devnet allocate coins to a *public* faucet key derived from a
constant seed. That key is deliberately published so anyone can run a wallet on
a test network; it is worthless and must never be used on mainnet. Mainnet
genesis has no allocations, exactly as PROTOCOL.md sections 12-13 require.

Usage::

    python scripts/make_genesis.py            # rewrite genesis/*.json
    python scripts/make_genesis.py --check    # fail if a file is out of date
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from sccp.chain.genesis import (
    FAUCET_SEEDS,
    GenesisAllocation,
    faucet_allocation,
    genesis_document,
)
from sccp.config import DEVNET, NETWORKS

ROOT = Path(__file__).resolve().parent.parent
GENESIS_DIR = ROOT / "genesis"

TIMESTAMPS = {
    "testnet": 1_700_000_000,
    "mainnet": 1_735_689_600,
    "devnet": DEVNET.genesis_timestamp or 1_700_000_000,
}


def allocations_for(network: str) -> tuple[GenesisAllocation, ...]:
    """The allocations a genesis document for ``network`` carries."""
    params = NETWORKS[network]
    return (faucet_allocation(network, params),) if network in FAUCET_SEEDS else ()


def document_for(network: str) -> dict[str, object]:
    """The genesis document for one network."""
    return genesis_document(
        NETWORKS[network],
        timestamp=TIMESTAMPS[network],
        allocations=allocations_for(network),
    )


def render(document: dict[str, object]) -> str:
    """Pretty, stable JSON with a trailing newline."""
    return json.dumps(document, indent=2, sort_keys=True) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="do not write; exit non-zero if a committed file is out of date",
    )
    args = parser.parse_args(argv)

    GENESIS_DIR.mkdir(exist_ok=True)
    failures = 0
    for network in sorted(NETWORKS):
        document = document_for(network)
        path = GENESIS_DIR / f"{network}.json"
        text = render(document)
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if args.check:
            if current != text:
                print(f"{path} is out of date; run scripts/make_genesis.py", file=sys.stderr)
                failures += 1
            continue
        path.write_text(text, encoding="utf-8")
        print(f"{network:8s} {document['hash']}  -> {path}")
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
