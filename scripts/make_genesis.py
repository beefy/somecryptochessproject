#!/usr/bin/env python3
"""Generate (or verify) the pinned genesis documents in ``genesis/``.

Genesis is the only place where supply can exist before a block subsidy, so it
is generated by a script and committed: the resulting hash is pinned in
:class:`sccp.config.NetworkParams` and checked on every load.

Mainnet allocates 1 basis point of the ZQWX cap (2,100 ZQWX) as a bootstrap
grant. There are no variant tranches: C960 exists only as mined supply and as
testnet liquidity. The public address and amount live in
``genesis/mainnet-premine.json``; its private key is deliberately not in this
repository. Testnet and devnet allocate coins
to a *public* faucet key derived from a constant seed, and testnet also seeds a
real ZQWX/C960 pool and a completed SCCP HTLC so a fresh deployment opens with a
usable DEX and bridge example.

Usage::

    python scripts/make_genesis.py            # rewrite genesis/*.json
    python scripts/make_genesis.py --check    # fail if a file is out of date
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from sccp.chain.genesis import (
    FAUCET_SEEDS,
    GenesisAllocation,
    GenesisHtlc,
    GenesisPool,
    faucet_allocation,
    genesis_document,
    testnet_bridge_hashlock,
    testnet_bridge_preimage,
    testnet_demo_keypair,
)
from sccp.chain.state import HtlcStatus
from sccp.config import CHESS960_ASSET_ID, DEVNET, NETWORKS, UNITS_PER_COIN, NetworkParams
from sccp.crypto.address import encode_address
from sccp.errors import ConfigError

ROOT = Path(__file__).resolve().parent.parent
GENESIS_DIR = ROOT / "genesis"
PREMINE_MANIFEST = GENESIS_DIR / "mainnet-premine.json"

TIMESTAMPS = {
    "testnet": 1_700_000_000,
    "mainnet": 1_735_689_600,
    "devnet": DEVNET.genesis_timestamp or 1_700_000_000,
}

TESTNET_DEMO_LIQUIDITY_COINS = 5
TESTNET_DEMO_BRIDGE_COINS = 1
TESTNET_DEMO_BRIDGE_NONCE = 1_000_000
"""The genesis-seeded testnet demo: 5 ZQWX/C960 per side and one claimed HTLC."""


def _mainnet_premine_allocations(params: NetworkParams) -> tuple[GenesisAllocation, ...]:
    """Read the public mainnet tranche manifest and turn it into allocations."""
    try:
        document = json.loads(PREMINE_MANIFEST.read_text(encoding="utf-8"))
    except OSError as exc:
        raise SystemExit(f"cannot read {PREMINE_MANIFEST}: {exc}") from exc
    except json.JSONDecodeError as exc:
        raise SystemExit(f"{PREMINE_MANIFEST} is not valid JSON: {exc}") from exc
    if not isinstance(document, dict) or document.get("network") != params.network_id:
        raise SystemExit(f"{PREMINE_MANIFEST} must be a {params.network_id} manifest")
    tranches = document.get("tranches")
    if not isinstance(tranches, list):
        raise SystemExit(f"{PREMINE_MANIFEST} needs a tranches list")

    allocations: list[GenesisAllocation] = []
    totals: dict[str, int] = {}
    for item in tranches:
        if not isinstance(item, dict):
            raise SystemExit("each premine tranche must be an object")
        label = item.get("label")
        asset = item.get("asset")
        basis_points = item.get("basis_points")
        address = item.get("address")
        public_key = item.get("public_key")
        if not all(isinstance(value, str) for value in (label, address, public_key)):
            raise SystemExit("a premine tranche needs label, address and public_key strings")
        if not isinstance(basis_points, int) or isinstance(basis_points, bool) or basis_points <= 0:
            raise SystemExit(f"premine tranche {label} needs positive integer basis_points")
        if asset == "ZQWX":
            selected = params.variant("standard")
            asset_id = ""
        elif isinstance(asset, str):
            try:
                selected = params.variant_for_asset(asset)
            except ConfigError as exc:
                raise SystemExit(
                    f"premine tranche {label} names unknown asset {asset}: {exc}"
                ) from None
            asset_id = selected.asset or ""
        else:
            raise SystemExit(f"premine tranche {label} needs an asset string")
        if selected.max_supply is None:
            raise SystemExit(f"premine tranche {label} needs a capped asset")
        amount = selected.max_supply * UNITS_PER_COIN * basis_points // 10_000
        if amount <= 0:
            raise SystemExit(f"premine tranche {label} rounds to zero")
        allocations.append(GenesisAllocation(address, public_key, amount, asset_id))
        totals[asset_id] = totals.get(asset_id, 0) + basis_points

    expected = {"": 1}
    if totals != expected:
        rendered = {asset or "ZQWX": value for asset, value in totals.items()}
        wanted = {asset or "ZQWX": value for asset, value in expected.items()}
        raise SystemExit(f"premine tranches total {rendered}, expected {wanted} basis points")
    return tuple(allocations)


def _testnet_demo(
    params: NetworkParams,
) -> tuple[tuple[GenesisAllocation, ...], tuple[GenesisPool, ...], tuple[GenesisHtlc, ...]]:
    """The testnet-only allocations, pool and bridge record committed at height 0."""
    liquidity = testnet_demo_keypair(0)
    beneficiary = testnet_demo_keypair(1)
    liquidity_address = encode_address(liquidity.public_key_bytes, params)
    beneficiary_address = encode_address(beneficiary.public_key_bytes, params)
    native = (TESTNET_DEMO_LIQUIDITY_COINS + TESTNET_DEMO_BRIDGE_COINS) * UNITS_PER_COIN
    variant = TESTNET_DEMO_LIQUIDITY_COINS * UNITS_PER_COIN
    allocations = (
        GenesisAllocation(liquidity_address, liquidity.public_key_hex, native),
        GenesisAllocation(
            liquidity_address,
            liquidity.public_key_hex,
            variant,
            CHESS960_ASSET_ID,
        ),
        GenesisAllocation(
            beneficiary_address,
            beneficiary.public_key_hex,
            TESTNET_DEMO_BRIDGE_COINS * UNITS_PER_COIN,
        ),
    )
    pools = (
        GenesisPool(
            creator=liquidity_address,
            asset_a="",
            amount_a=TESTNET_DEMO_LIQUIDITY_COINS * UNITS_PER_COIN,
            asset_b=CHESS960_ASSET_ID,
            amount_b=TESTNET_DEMO_LIQUIDITY_COINS * UNITS_PER_COIN,
        ),
    )
    htlcs = (
        GenesisHtlc(
            sender=liquidity_address,
            beneficiary=beneficiary_address,
            hashlock=testnet_bridge_hashlock(),
            amount=TESTNET_DEMO_BRIDGE_COINS * UNITS_PER_COIN,
            timelock_height=1_000,
            status=HtlcStatus.CLAIMED,
            preimage=testnet_bridge_preimage(),
            created_at_height=0,
            closed_at_height=0,
            nonce=TESTNET_DEMO_BRIDGE_NONCE,
        ),
    )
    return allocations, pools, htlcs


def pools_for(network: str) -> tuple[GenesisPool, ...]:
    """The genesis pools for ``network``; only testnet seeds one today."""
    return _testnet_demo(NETWORKS[network])[1] if network == "testnet" else ()


def htlcs_for(network: str) -> tuple[GenesisHtlc, ...]:
    """The genesis HTLC records for ``network``; only testnet seeds one today."""
    return _testnet_demo(NETWORKS[network])[2] if network == "testnet" else ()


def allocations_for(network: str) -> tuple[GenesisAllocation, ...]:
    """The allocations a genesis document for ``network`` carries."""
    params = NETWORKS[network]
    if network == "mainnet":
        return _mainnet_premine_allocations(params)
    entries = (faucet_allocation(network, params),) if network in FAUCET_SEEDS else ()
    if network == "testnet":
        return entries + _testnet_demo(params)[0]
    return entries


def document_for(network: str) -> dict[str, object]:
    """The genesis document for one network."""
    return genesis_document(
        NETWORKS[network],
        timestamp=TIMESTAMPS[network],
        allocations=allocations_for(network),
        pools=pools_for(network),
        htlcs=htlcs_for(network),
    )


def render(document: dict[str, object]) -> str:
    """Pretty, stable JSON with a trailing newline."""
    return json.dumps(document, indent=2, sort_keys=True) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="do not write; exit non-zero if a committed file is out of date",
    )
    args = parser.parse_args(argv)

    GENESIS_DIR.mkdir(exist_ok=True)
    failures = 0
    for network in sorted(NETWORKS):
        document = document_for(network)
        path = GENESIS_DIR / f"{network}.json"
        text = render(document)
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if args.check:
            if current != text:
                print(f"{path} is out of date; run scripts/make_genesis.py", file=sys.stderr)
                failures += 1
            continue
        path.write_text(text, encoding="utf-8")
        print(f"{network:8s} {document['hash']}  -> {path}")
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
